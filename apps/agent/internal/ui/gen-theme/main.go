// Command gen-theme turns docs/design/tokens.json into theme_gen.go so the CLI
// colours always come from the shared design tokens.
//
//	go run ./internal/ui/gen-theme -in ../../docs/design/tokens.json -out internal/ui/theme_gen.go
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
)

type palette struct{ Text, Muted, Faint, Accent, Border string }

type status struct {
	Shape, Glyph, Light, Dark string
	BadgeBg                   string `json:"badgeBg"`
	BadgeFg                   string `json:"badgeFg"`
}

type tokens struct {
	Version int                `json:"version"`
	Palette map[string]palette `json:"palette"`
	Status  map[string]status  `json:"status"`
}

func main() {
	in := flag.String("in", "../../docs/design/tokens.json", "token source")
	out := flag.String("out", "internal/ui/theme_gen.go", "generated file")
	flag.Parse()
	raw, err := os.ReadFile(*in)
	if err != nil {
		fail(err)
	}
	var t tokens
	if err := json.Unmarshal(raw, &t); err != nil {
		fail(err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/ui/gen-theme from docs/design/tokens.json (version %d); DO NOT EDIT.\n\npackage ui\n\n", t.Version)
	for _, mode := range []string{"light", "dark"} {
		p, ok := t.Palette[mode]
		if !ok {
			fail(fmt.Errorf("palette.%s missing", mode))
		}
		fmt.Fprintf(&b, "var palette%s = Palette{Text: %q, Muted: %q, Faint: %q, Accent: %q, Border: %q}\n\n", title(mode), p.Text, p.Muted, p.Faint, p.Accent, p.Border)
	}
	names := make([]string, 0, len(t.Status))
	for n := range t.Status {
		names = append(names, n)
	}
	sort.Strings(names)
	b.WriteString("var statusTokens = map[string]StatusToken{\n")
	for _, n := range names {
		s := t.Status[n]
		fmt.Fprintf(&b, "\t%q: {Shape: %q, Glyph: %q, Light: %q, Dark: %q, BadgeBg: %q, BadgeFg: %q},\n", n, s.Shape, s.Glyph, s.Light, s.Dark, s.BadgeBg, s.BadgeFg)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fail(err)
	}
}

func title(s string) string { return string(s[0]-32) + s[1:] }

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen-theme:", err)
	os.Exit(1)
}
