#!/usr/bin/env bash
# Set up Orion Core with Docker in one command.
#
#   curl -fsSL https://raw.githubusercontent.com/sunday-studio/orion/main/deploy/scripts/setup-core.sh | bash
#
# What it does: checks Docker, creates ./orion with docker-compose.yml and a .env holding freshly
# generated secrets, starts Core and its monitor worker, waits until Core is healthy and prints the
# Console address, the login, and the command that connects a server.
# It never overwrites an existing .env. Running it again just starts Core and reprints the summary.
#
# Options (or the matching environment variable):
#   --dir <path>          Install folder (ORION_DIR, default ./orion)
#   --public-url <url>    Address people and servers reach Core on, for example https://orion.example.com
#                         (ORION_PUBLIC_URL). Default: http://<this server's IP>:<port>
#   --version <version>   Core image tag, for example 0.2.1 (ORION_VERSION, default below)
#   --port <port>         Port on this machine (ORION_HTTP_PORT, default 8999)
#   --ref <git ref>       Where to download compose files from (ORION_REF, default main)
#   --no-start            Write the files and stop before starting Core
#   -h, --help            Show this help
set -euo pipefail

DEFAULT_VERSION="0.2.1"
REPO="sunday-studio/orion"

DIR="${ORION_DIR:-./orion}"
PUBLIC_URL="${ORION_PUBLIC_URL:-}"
VERSION="${ORION_VERSION:-$DEFAULT_VERSION}"
PORT="${ORION_HTTP_PORT:-8999}"
REF="${ORION_REF:-main}"
START=true

die() { printf 'error: %s\n' "$1" >&2; [ -n "${2:-}" ] && printf '  fix: %s\n' "$2" >&2; exit 1; }
info() { printf '  %s\n' "$*"; }
usage() { sed -n '2,19p' "$0" | sed 's/^# \{0,1\}//'; }

# The address this server answers on, used when --public-url is not given.
detect_address() {
  local ip=""
  if command -v hostname >/dev/null 2>&1; then ip="$(hostname -I 2>/dev/null | awk '{print $1}')"; fi
  if [ -z "$ip" ] && command -v ipconfig >/dev/null 2>&1; then ip="$(ipconfig getifaddr en0 2>/dev/null || ipconfig getifaddr en1 2>/dev/null || true)"; fi
  if [ -z "$ip" ] && command -v ip >/dev/null 2>&1; then ip="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src") print $(i+1)}' | head -n1)"; fi
  printf '%s' "$ip"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --dir) DIR="${2:?--dir needs a path}"; shift 2 ;;
    --public-url) PUBLIC_URL="${2:?--public-url needs a URL}"; shift 2 ;;
    --version) VERSION="${2:?--version needs a value}"; shift 2 ;;
    --port) PORT="${2:?--port needs a number}"; shift 2 ;;
    --ref) REF="${2:?--ref needs a git ref}"; shift 2 ;;
    --no-start) START=false; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown option: $1" "run with --help to see the options" ;;
  esac
done

printf 'Orion Core setup\n\n'

# ---------------------------------------------------------------- prerequisites
command -v docker >/dev/null 2>&1 || die "Docker is not installed" "install Docker Engine: https://docs.docker.com/engine/install/"
docker compose version >/dev/null 2>&1 || die "the Docker Compose plugin is missing" "install it: https://docs.docker.com/compose/install/"
docker info >/dev/null 2>&1 || die "cannot talk to the Docker daemon" "start Docker, or add your user to the docker group, then retry"
command -v curl >/dev/null 2>&1 || die "curl is not installed" "install curl"
command -v openssl >/dev/null 2>&1 || die "openssl is not installed" "install openssl (used only to generate secrets)"
info "ok  docker, compose, curl and openssl found"

# ---------------------------------------------------------------- address
if [ -z "$PUBLIC_URL" ]; then
  ADDRESS="$(detect_address)"
  [ -n "$ADDRESS" ] || die "could not work out this server's address" "re-run with --public-url http://<server-ip>:${PORT} or your domain"
  PUBLIC_URL="http://${ADDRESS}:${PORT}"
  info "ok  using ${PUBLIC_URL} (pass --public-url to use a domain)"
else
  info "ok  using ${PUBLIC_URL}"
fi

# ---------------------------------------------------------------- files
BASE_URL="https://raw.githubusercontent.com/${REPO}/${REF}/deploy"
mkdir -p "$DIR"
cd "$DIR"
curl -fsSL "$BASE_URL/docker-compose.yml" -o docker-compose.yml || die "could not download docker-compose.yml from $BASE_URL" "check your network and --ref"
curl -fsSL "$BASE_URL/.env.example" -o .env.example || die "could not download .env.example" "check your network and --ref"
info "ok  compose files in $(pwd)"

CREATED_ENV=false
if [ -f .env ]; then
  info "ok  keeping your existing .env"
else
  umask 077
  ADMIN_PASSWORD="$(openssl rand -base64 24 | tr -d '/+=')"
  JWT_SECRET="$(openssl rand -hex 32)"
  ENROLLMENT_TOKEN="$(openssl rand -hex 16)"
  EMAIL_SECRET="$(openssl rand -hex 32)"
  {
    echo "# Generated by setup-core.sh. Options: docs/deployment/core-environment.md"
    echo "ORION_ADMIN_USERNAME=admin"
    echo "ORION_ADMIN_PASSWORD=${ADMIN_PASSWORD}"
    echo "ORION_JWT_SECRET=${JWT_SECRET}"
    echo "ORION_ENROLLMENT_TOKEN=${ENROLLMENT_TOKEN}"
    echo "ORION_ALERT_EMAIL_SECRET=${EMAIL_SECRET}"
    echo "ORION_CORE_IMAGE=ghcr.io/sunday-studio/orion-core:${VERSION}"
    echo "ORION_HTTP_PORT=${PORT}"
    echo "ORION_PUBLIC_URL=${PUBLIC_URL}"
  } > .env
  chmod 600 .env
  CREATED_ENV=true
  info "ok  wrote .env with generated secrets (mode 600)"
fi

env_value() { grep -E "^$1=" .env | tail -n1 | cut -d= -f2- || true; }

[ "$START" = true ] || { printf '\nFiles written. Start Core with:  cd %s && docker compose up -d\n' "$(pwd)"; exit 0; }

# ---------------------------------------------------------------- start
printf '\nStarting Core (the first run pulls the image)...\n'
docker compose pull --quiet || die "could not pull the Core image" "check ORION_CORE_IMAGE in .env, your network, and that the version exists"
docker compose up -d

PORT_NOW="$(env_value ORION_HTTP_PORT)"; PORT_NOW="${PORT_NOW:-8999}"
printf 'Waiting for Core to become healthy'
for _ in $(seq 1 60); do
  if curl -fsS "http://127.0.0.1:${PORT_NOW}/health" >/dev/null 2>&1; then HEALTHY=true; break; fi
  printf '.'; sleep 2
done
printf '\n'
[ "${HEALTHY:-false}" = true ] || die "Core did not become healthy within two minutes" "run: cd $(pwd) && docker compose logs orion-core"

# ---------------------------------------------------------------- summary
URL="$(env_value ORION_PUBLIC_URL)"; URL="${URL:-$PUBLIC_URL}"
printf '\nOrion Core is running.\n\n'
printf '  Console   %s\n' "$URL"
printf '  Login     %s  /  %s\n' "$(env_value ORION_ADMIN_USERNAME)" "$(env_value ORION_ADMIN_PASSWORD)"
printf '  Folder    %s\n' "$(pwd)"
[ "$CREATED_ENV" = true ] && printf '\nThe password is stored in %s/.env. Change it by editing .env and running: docker compose up -d\n' "$(pwd)"
TOKEN="$(env_value ORION_ENROLLMENT_TOKEN)"
printf '\nOpen the Console from your own computer at the address above. If it does not load, allow TCP port %s\n' "$PORT_NOW"
printf 'through this server'"'"'s firewall or security group. For HTTPS on a domain, put a reverse proxy in front of Core and set\n'
printf 'ORION_PUBLIC_URL in %s/.env (see docs/getting-started.md).\n' "$(pwd)"
printf '\nNext: connect a server. In the Console choose Servers, then Add server, and run the command it shows on\n'
printf 'the machine you want to watch (Linux or macOS). Or run this there, with a Core address it can reach:\n\n'
printf '  curl -fsSL https://github.com/%s/releases/latest/download/orion-node-installer.sh | \\\n' "$REPO"
if [ -n "$TOKEN" ]; then
  printf '    ORION_ENROLLMENT_TOKEN=%s bash -s -- --core-url %s\n\n' "$TOKEN" "$URL"
else
  printf '    bash -s -- --core-url %s   # add a one-time token from Console > Add server\n\n' "$URL"
fi
printf 'Docs: https://orion.thesunday.studio/docs/\n'
